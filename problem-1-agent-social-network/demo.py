# ── helpers ───────────────────────────────────────────────────────────────────

def load_credentials() -> dict[str, dict]:
    """Load agents_credentials.json → {company: cred_dict}."""
    if not CREDENTIALS_FILE.exists():
        fatal(f"{CREDENTIALS_FILE} not found. Run  python seed_agents.py  first.")
        sys.exit(1)
    raw: list[dict] = json.loads(CREDENTIALS_FILE.read_text(encoding="utf-8"))
    return {c["company"]: c for c in raw}


def fetch_post_comments(client: httpx.Client, post_id: str) -> list[dict]:
    """Return the comments list for a given post."""
    try:
        resp = client.get(f"{BASE_URL}/posts/{post_id}/comments", timeout=20)
        resp.raise_for_status()
        return resp.json()
    except (httpx.HTTPStatusError, httpx.RequestError):
        return []


def fetch_global_feed(client: httpx.Client) -> list[dict]:
    """Return the global feed (all posts, most recent first)."""
    try:
        resp = client.get(f"{BASE_URL}/feed", timeout=20)
        resp.raise_for_status()
        return resp.json()
    except (httpx.HTTPStatusError, httpx.RequestError):
        return []


def publish_post(
    client: httpx.Client,
    company: str,
    payload: dict,
    credentials: dict[str, dict],
    post_number: int,
    total: int,
) -> dict | None:
    """Publish one post and pretty-print the routing + comment results."""
    cred = credentials.get(company)
    if not cred:
        warn(f"No credentials for {company} – skipping post.")
        return None

    banner(
        f"POST {post_number}/{total}  ·  {company}",
        color=CYAN,
    )
    print(f"\n  Content: {payload['content'][:90]}{'…' if len(payload['content']) > 90 else ''}")
    print(f"  Tags:    {', '.join(payload['tags'])}\n")

    headers = {"X-API-Key": cred["api_key"]}
    try:
        resp = client.post(
            f"{BASE_URL}/posts",
            json=payload,
            headers=headers,
            timeout=90,
        )
        resp.raise_for_status()
        data = resp.json()
    except httpx.HTTPStatusError as exc:
        fatal(f"HTTP {exc.response.status_code}: {exc.response.text}")
        return None
    except httpx.RequestError as exc:
        fatal(f"Connection error – {exc}")
        return None

    post = data.get("post", {})
    post_id = post.get("id", "")
    item("Post ID", post_id or "N/A")

    # ── Routing results ───────────────────────────────────────────────────────
    routing = data.get("routing", {})
    notified = routing.get("notified_agents", [])
    section(f"Agents notified  ({len(notified)})")
    if notified:
        for n in sorted(notified, key=lambda x: x.get("relevance_score", 0), reverse=True):
            score = n.get("relevance_score", 0)
            agent_label = n.get("company", n.get("agent_id", "?"))
            bar_len = int(score * 20)
            bar = "█" * bar_len + "░" * (20 - bar_len)
            print(f"      {agent_label:<20}  [{bar}]  {score:.2f}")
    else:
        warn("No agents were notified (threshold not met or no other agents).")

    # ── Auto-comments ─────────────────────────────────────────────────────────
    # Give the server a moment if comments are async
    if post_id:
        time.sleep(1)
        comments = fetch_post_comments(client, post_id)
    else:
        comments = data.get("comments", [])

    section(f"Auto-comments generated  ({len(comments)})")
    if comments:
        for c in comments:
            agent_label = c.get("agent_company", c.get("agent_id", "?"))
            content = c.get("content", "")
            print(f"\n      [{BOLD}{agent_label}{RESET}]")
            # Word-wrap to ~65 chars
            words = content.split()
            line, lines = [], []
            for w in words:
                if sum(len(x) + 1 for x in line) + len(w) > 65:
                    lines.append(" ".join(line))
                    line = [w]
                else:
                    line.append(w)
            if line:
                lines.append(" ".join(line))
            for ln in lines:
                print(f"        {ln}")
    else:
        print("      (no comments yet)")

    return data


def print_global_feed(feed: list[dict]) -> None:
    """Pretty-print the global feed."""
    banner("GLOBAL FEED", color=YELLOW)
    if not feed:
        warn("Feed is empty.")
        return

    for i, post in enumerate(feed, 1):
        agent_info = post.get("agent", {})
        company = agent_info.get("company", post.get("agent_id", "?"))
        content = post.get("content", "")
        tags = post.get("tags", [])
        created = post.get("created_at", "")

        print(f"\n  {DIM}#{i}{RESET}  {BOLD}{company}{RESET}  {DIM}{created}{RESET}")
        snippet = content[:100] + ("…" if len(content) > 100 else "")
        print(f"      {snippet}")
        if tags:
            tag_str = "  ".join(f"#{t}" for t in tags)
            print(f"      {DIM}{tag_str}{RESET}")

    print()


# ── entry point ───────────────────────────────────────────────────────────────

def main() -> None:
    banner("🤖  AI Agent Social Network – Full Demo", color=GREEN)
    print(f"  API: {BASE_URL}")

    credentials = load_credentials()
    print(f"  Loaded credentials for: {', '.join(credentials.keys())}\n")

    with httpx.Client() as client:
        total = len(DEMO_POSTS)
        for i, demo in enumerate(DEMO_POSTS, 1):
            publish_post(
                client,
                company=demo["company"],
                payload=demo["payload"],
                credentials=credentials,
                post_number=i,
                total=total,
            )
            if i < total:
                # Brief pause between posts so routing results stay readable
                time.sleep(0.5)

        # ── Global feed ───────────────────────────────────────────────────────
        feed = fetch_global_feed(client)
        print_global_feed(feed)

    banner("✅  Demo complete", color=GREEN)
    print("  Explore the API at http://localhost:8000/docs\n")


if __name__ == "__main__":
    main()
