# ── pretty helpers ────────────────────────────────────────────────────────────

RESET = "\033[0m"
BOLD = "\033[1m"
CYAN = "\033[96m"
GREEN = "\033[92m"
YELLOW = "\033[93m"
RED = "\033[91m"
DIM = "\033[2m"


def banner(text: str, color: str = CYAN) -> None:
    width = 72
    print(f"\n{color}{BOLD}{'═' * width}{RESET}")
    print(f"{color}{BOLD}  {text}{RESET}")
    print(f"{color}{BOLD}{'═' * width}{RESET}")


def section(text: str) -> None:
    print(f"\n{YELLOW}{BOLD}  ▶ {text}{RESET}")


def item(label: str, value: str, indent: int = 4) -> None:
    pad = " " * indent
    print(f"{pad}{GREEN}✔{RESET}  {BOLD}{label}:{RESET} {value}")


def bullet(text: str, indent: int = 6) -> None:
    pad = " " * indent
    print(f"{pad}•  {text}")


def warn(text: str) -> None:
    print(f"  {YELLOW}⚠{RESET}  {text}")


def fatal(text: str) -> None:
    print(f"  {RED}✘  {text}{RESET}", file=sys.stderr)


