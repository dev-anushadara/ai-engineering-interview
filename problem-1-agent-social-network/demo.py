"""
demo.py – Rich end-to-end demo of the AI Agent Social Network.

Usage:
    python seed_agents.py   # run first to populate agents_credentials.json
    python demo.py

Requires:
    - API server running at http://localhost:8000
    - agents_credentials.json present (generated by seed_agents.py)
    - httpx installed (pip install httpx)
"""

import json
